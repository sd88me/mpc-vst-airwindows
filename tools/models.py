"""The airwindows model list, read from the vendored airwin2rack registry (vendor/airwin2rack/src/ModuleAdd.h).

models() -> [{name, category, order, what, date, collections}] in Chris's order within each category.
A category upstream leaves "Unclassified" takes tools/category_overrides.tsv's entry when there is one
(the overrides come from charlesvestal/schwung-airwindows; upstream wins as soon as it classifies an effect).
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
VENDOR = os.path.join(ROOT, "vendor", "airwin2rack")

REG = re.compile(r'registerAirwindow\(\{"([^"]+)", "([^"]*)", (-?\d+), (true|false), "((?:[^"\\]|\\.)*)", '
                 r'airwinconsolidated::\w+::kNumParameters, "([^"]*)", .*?\{ ?([^}]*)\}\}\);')


def overrides():
    out = {}
    for line in open(os.path.join(HERE, "category_overrides.tsv")):
        line = line.rstrip("\n")
        if line and not line.startswith("#") and "\t" in line:
            name, cat = line.split("\t", 1)
            out[name.strip()] = cat.strip()
    return out


def models():
    ov = overrides()
    out = []
    for line in open(os.path.join(VENDOR, "src", "ModuleAdd.h")):
        m = REG.search(line)
        if not m:
            continue
        name, cat, order, _mono, what, date, coll = m.groups()
        if cat == "Unclassified" and name in ov:
            cat = ov[name]
        out.append({"name": name, "category": cat, "order": int(order),
                    "what": what.encode().decode("unicode_escape") if "\\" in what else what,
                    "date": date, "collections": re.findall(r'"([^"]+)"', coll)})
    out.sort(key=lambda m: (m["category"], m["order"], m["name"]))
    return out


def slug(category):
    return re.sub(r"[^A-Za-z0-9]+", "", category.title())


def table_cpp(ms, slot_maps=None):
    """C++ source: a {name, params, factory} table of the given models (src/models.h). Each factory lives in its
    own file (factory_cpp): some upstream headers share include guards, so they can't all go in one file."""
    lines = ['// Generated by tools/gen_categories.py from the vendored airwin2rack registry: do not edit.',
             '#include "models.h"']
    lines += ["AirwinConsolidatedBase *aw_new_%s(); int aw_np_%s();" % (m["name"], m["name"]) for m in ms]
    lines.append("const aw_model_t AW_MODELS[] = {")
    lines += ['    {"%s", aw_np_%s, aw_new_%s},' % (m["name"], m["name"], m["name"]) for m in ms]
    lines.append("};")
    lines.append("const int AW_NUM_MODELS = %d;" % len(ms))
    maps = slot_maps or {}
    for m in ms:
        if m["name"] in maps:
            lines.append("static const int aw_map_%s[] = {%s};" % (m["name"], ", ".join(str(i) for i in maps[m["name"]])))
    lines.append("const int *const AW_SLOT_MAP[] = {%s};" % ", ".join("aw_map_%s" % m["name"] if m["name"] in maps else "nullptr" for m in ms))
    lines.append("const int AW_SLOT_MAP_LEN[] = {%s};" % ", ".join(str(len(maps.get(m["name"], []))) for m in ms))
    return "\n".join(lines) + "\n"


def factory_cpp(name):
    return ('// Generated by tools/gen_categories.py: do not edit.\n#include "autogen_airwin/%s.h"\n'
            'AirwinConsolidatedBase *aw_new_%s() { return new airwinconsolidated::%s::%s(0); }\n'
            'int aw_np_%s() { return airwinconsolidated::%s::kNumParameters; }\n') % ((name,) * 6)


def sources(ms):
    """Every .cpp a model needs, relative to vendor/airwin2rack/src."""
    out = []
    for m in ms:
        for f in ("%s.cpp" % m["name"], "%sProc.cpp" % m["name"]):
            if os.path.exists(os.path.join(VENDOR, "src", "autogen_airwin", f)):
                out.append("autogen_airwin/" + f)
    return out
