#!/usr/bin/env python3
"""Write docs/STATUS.md: one row per collection (category plugin) with what is generated, built and known on devices.

    tools/status.py

Models, control slots and pages come from vst/<Slug>/gen/skin_models.json; "built" from the .so files under
vst/<Slug>/build/ (armv7 = Force and Gen1, aarch64/ = Gen2); device facts from docs/status.json (kept by hand).
"""
import glob
import json
import math
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def main():
    facts = json.load(open(os.path.join(ROOT, "docs", "status.json")))
    rows, tot = [], 0
    for f in sorted(glob.glob(os.path.join(ROOT, "vst", "*", "gen", "skin_models.json"))):
        d = json.load(open(f)); port = os.path.dirname(os.path.dirname(f)); b = os.path.join(port, "build")
        so = os.path.basename(json.load(open(os.path.join(port, "vst.json")))["so"])
        a7 = os.path.exists(os.path.join(b, so)); a64 = os.path.exists(os.path.join(b, "aarch64", so))
        fx = facts.get(d["category"], {}); tot += len(d["models"])
        sp = os.path.join(ROOT, "docs", "summaries", os.path.basename(port) + ".json")
        ns = len(json.load(open(sp))) if os.path.exists(sp) else 0
        rows.append("| %s | %s | %d | %d | %d | %s | %s | %s | %s | %s | %s |" % (
            d["category"], d["name"], len(d["models"]), d["slots"], max(1, math.ceil(d["slots"] / 14)), ("%d / %d" % (ns, len(d["models"]))) if ns else "-",
            "yes" if a7 else "-", "yes" if a64 else "-", fx.get("force", "-"), fx.get("live3", "-"), fx.get("notes", "")))
    out = ["# Collections: what is built and where", "",
           "Generated by `tools/status.py` (built files are read from `vst/*/build/`; device facts from `docs/status.json`).", "",
           "One plugin per upstream airwindows category, each with a Model selector. %d models in %d collections." % (tot, len(rows)), "",
           "| Category | Plugin | Models | Slots | Pages | Summaries | armv7 | aarch64 | Force | Live 3 | Notes |", "|---|---|---|---|---|---|---|---|---|---|---|"] + rows
    if facts.get("_planned"):
        out += ["", "## Planned", ""] + ["- **%s** (%d models): %s" % (p["plugin"], p["models"], p["notes"]) for p in facts["_planned"]]
    open(os.path.join(ROOT, "docs", "STATUS.md"), "w").write("\n".join(out) + "\n")
    print("docs/STATUS.md: %d collections" % len(rows))


if __name__ == "__main__":
    main()
